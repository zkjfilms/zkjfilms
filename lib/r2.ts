// S3-compatible client for Cloudflare R2, used by the client gallery
// feature to store and serve photos and videos.

import { createHash } from "node:crypto";
import { extname } from "node:path";
import {
  GetObjectCommand,
  ListObjectsV2Command,
  S3Client,
} from "@aws-sdk/client-s3";
import { getSignedUrl } from "@aws-sdk/s3-request-presigner";
import { requireEnv } from "@/lib/env";

const R2_BUCKET_NAME = process.env.R2_BUCKET_NAME ?? "";

function getR2Client(): S3Client {
  return new S3Client({
    region: "auto",
    endpoint: requireEnv("R2_ENDPOINT"),
    credentials: {
      accessKeyId: requireEnv("R2_ACCESS_KEY_ID"),
      secretAccessKey: requireEnv("R2_SECRET_ACCESS_KEY"),
    },
  });
}

export type GalleryMedia = {
  key: string;
  url: string;
  // Small/medium WebP renditions for the grid and lightbox (see
  // galleryPreviewKeys). Fall back to `url` (the original) for videos and
  // for photos uploaded before previews existed / not yet backfilled.
  thumbUrl: string;
  previewUrl: string;
  downloadUrl: string;
  filename: string;
  isVideo: boolean;
  // Bytes of the original, and of the large WebP preview when one exists
  // (null otherwise) — used to label download buttons with a total size.
  size: number;
  previewSize: number | null;
};

// A ready-made zip of the whole gallery's originals, built and uploaded by
// `npm run gallery:upload` / `gallery:zip`. Null when there isn't one or
// it's out of date — the UI then builds the zip in the browser instead.
export type GalleryZip = {
  url: string;
  size: number;
};

export type GalleryListing = {
  images: GalleryMedia[];
  fullZip: GalleryZip | null;
};

// Downsized WebP copies of each gallery photo, generated by
// `npm run gallery:upload` / `gallery:previews` (scripts/gallery.mjs —
// keep the key layout in sync by hand). They live outside galleries/<slug>/
// on purpose so the listing below, favorites and zip downloads only ever
// see the originals.
export function galleryPreviewKeys(slug: string, filename: string) {
  return {
    thumb: `gallery-previews/${slug}/thumb/${filename}.webp`,
    large: `gallery-previews/${slug}/large/${filename}.webp`,
  };
}

// The prebuilt zip is stored as gallery-zips/<slug>/<fingerprint>.zip,
// where the fingerprint is a hash of every original's filename + ETag at
// build time. Any later change to the gallery (a photo added, removed or
// re-uploaded) changes the fingerprint, so a stale zip simply doesn't
// match and is never served. scripts/gallery.mjs galleryFingerprint() must
// compute exactly the same value.
function galleryFingerprint(objects: { filename: string; etag: string }[]): string {
  const lines = objects
    .map((o) => `${o.filename}\t${o.etag.replaceAll('"', "")}`)
    .sort();
  return createHash("sha256").update(lines.join("\n")).digest("hex").slice(0, 16);
}

type ListedObject = { Key: string; Size: number; ETag: string };

async function listAllObjects(client: S3Client, prefix: string): Promise<ListedObject[]> {
  const objects: ListedObject[] = [];
  let ContinuationToken: string | undefined;
  do {
    const page = await client.send(
      new ListObjectsV2Command({ Bucket: R2_BUCKET_NAME, Prefix: prefix, ContinuationToken }),
    );
    for (const obj of page.Contents ?? []) {
      if (obj.Key && !obj.Key.endsWith("/")) {
        objects.push({ Key: obj.Key, Size: obj.Size ?? 0, ETag: obj.ETag ?? "" });
      }
    }
    ContinuationToken = page.IsTruncated ? page.NextContinuationToken : undefined;
  } while (ContinuationToken);
  return objects;
}

export const SIGNED_URL_EXPIRY_SECONDS = 60 * 60; // 1 hour

// Kept in sync with UPLOAD_CONTENT_TYPES's video entries in
// scripts/gallery.mjs by hand — that script can't import this file since
// it runs as plain Node, not through Next/TypeScript.
const VIDEO_EXTENSIONS = new Set([".mp4"]);

function isVideoFile(filename: string): boolean {
  return VIDEO_EXTENSIONS.has(extname(filename).toLowerCase());
}

// A gallery can hold a mix of photos and short client-delivery videos —
// this list treats them uniformly (same signed-URL mechanism, same
// listing) and just tags each item so the UI knows how to render it.
//
// Media for a gallery lives under galleries/<slug>/ in the bucket. Signed
// URLs expire after an hour — a client browsing longer than that in one
// sitting would need to re-unlock to get fresh URLs. (A download that has
// already started keeps going past expiry; only new requests are refused.)
//
// Two signed URLs per item: `url` for inline display/playback, and
// `downloadUrl` with a Content-Disposition override so browsers reliably
// save it as a file with the right name instead of navigating to it — the
// plain HTML `download` attribute isn't consistently honored for
// cross-origin URLs. Both work identically for photos and videos — R2
// presigned GET URLs support HTTP Range requests regardless of content
// type, so video seeking/scrubbing works the same way it does for the
// public showcase videos (app/films).
export async function listGallery(slug: string): Promise<GalleryListing> {
  const client = getR2Client();
  const prefix = `galleries/${slug}/`;

  const [objects, previewObjects, zipObjects] = await Promise.all([
    listAllObjects(client, prefix),
    listAllObjects(client, `gallery-previews/${slug}/`),
    listAllObjects(client, `gallery-zips/${slug}/`),
  ]);
  const previewSizes = new Map(previewObjects.map((o) => [o.Key, o.Size]));

  const sign = (Key: string, downloadAs?: string) =>
    getSignedUrl(
      client,
      new GetObjectCommand({
        Bucket: R2_BUCKET_NAME,
        Key,
        ResponseContentDisposition: downloadAs
          ? `attachment; filename="${downloadAs}"`
          : undefined,
      }),
      { expiresIn: SIGNED_URL_EXPIRY_SECONDS },
    );

  const images = await Promise.all(
    objects.map(async (obj): Promise<GalleryMedia> => {
      const filename = obj.Key.slice(prefix.length);
      const isVideo = isVideoFile(filename);
      const preview = galleryPreviewKeys(slug, filename);
      const hasPreviews =
        !isVideo && previewSizes.has(preview.thumb) && previewSizes.has(preview.large);

      const [url, downloadUrl, thumbUrl, previewUrl] = await Promise.all([
        sign(obj.Key),
        sign(obj.Key, filename),
        hasPreviews ? sign(preview.thumb) : null,
        hasPreviews ? sign(preview.large) : null,
      ]);

      return {
        key: obj.Key,
        url,
        thumbUrl: thumbUrl ?? url,
        previewUrl: previewUrl ?? url,
        downloadUrl,
        filename,
        isVideo,
        size: obj.Size,
        previewSize: hasPreviews ? (previewSizes.get(preview.large) ?? null) : null,
      };
    }),
  );

  const fingerprint = galleryFingerprint(
    objects.map((o) => ({ filename: o.Key.slice(prefix.length), etag: o.ETag })),
  );
  const zipObject = zipObjects.find(
    (o) => o.Key === `gallery-zips/${slug}/${fingerprint}.zip`,
  );
  const fullZip =
    objects.length > 0 && zipObject
      ? { url: await sign(zipObject.Key, `${slug}.zip`), size: zipObject.Size }
      : null;

  return { images, fullZip };
}
